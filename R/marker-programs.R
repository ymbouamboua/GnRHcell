#' GnRH developmental and functional marker gene references
#'
#' Returns a gene-level reference table describing curated GnRH developmental
#' and secretory programs.
#'
#' @return Data frame containing gene, program, dimension, evidence class,
#'   and reference information.
#'
#' @export
gnrh_stage_gene_references <- function() {
  developmental <- gnrh_stage_modules()
  secretory <- gnrh_secretory_marker_module()

  modules <- c(
    developmental,
    list(secretory = secretory)
  )

  dimension_map <- c(
    identity = "developmental",
    migrating = "developmental",
    mature = "developmental",
    secretory = "functional"
  )

  evidence_map <- c(
    identity = "developmental_identity",
    migrating = "migration_guidance",
    mature = "neuroendocrine_maturation",
    secretory = "secretory_machinery"
  )

  ref_map <- c(
    identity = paste(
      "Wray 2010;",
      "Stevenson et al. 2013;",
      "Cho et al. 2019"
    ),

    migrating = paste(
      "Schwanzel-Fukuda & Pfaff 1989;",
      "Wray 2010;",
      "Cho et al. 2019;",
      "Taroc et al. 2019"
    ),

    mature = paste(
      "Wray 2010;",
      "Stevenson et al. 2013"
    ),

    secretory = paste(
      "Wray 2010;",
      "general neuroendocrine secretory machinery"
    )
  )

  out <- lapply(
    names(modules),
    function(program) {
      data.frame(
        gene = modules[[program]],
        program = program,
        dimension = dimension_map[[program]],
        evidence_class = evidence_map[[program]],
        references = ref_map[[program]],
        stringsAsFactors = FALSE
      )
    }
  )

  out <- do.call(rbind, out)
  rownames(out) <- NULL

  unique(out)
}



